const express= require("express")
const errorHandler= require("./middlewares/errorHandler")
const apiVersion= require("./middlewares/apiVersion")
const { authLimiter, apiLimiter, analyticsLimiter, speedLimiter }= require("./middlewares/rateLimiters")
const v1Routes= require("./routes/v1")
const v2Routes= require("./routes/v2")
const app= express()
app.set("trust proxy", 1)
app.get("/healthz/liveness", (req, res)=> res.status(200).json({ status: "ok" }))
app.use(express.json())
app.use(["/api/v1/auth", "/api/v2/auth"], speedLimiter, authLimiter)
app.use("/api/v2/analytics", speedLimiter, analyticsLimiter)
app.use("/api", apiLimiter)
app.use("/api/v1", apiVersion("1.0.0", true), v1Routes)
app.use("/api/v2", apiVersion("2.0.0", false), v2Routes)
app.use(errorHandler)
module.exports= app