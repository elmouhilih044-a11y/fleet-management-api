const mockSend= jest.fn()
jest.mock("@aws-sdk/client-s3", ()=> ({ S3Client: jest.fn(()=> ({ send: mockSend })), PutObjectCommand: jest.fn((input)=> ({ input })), GetObjectCommand: jest.fn((input)=> ({ input })) }))
jest.mock("@aws-sdk/s3-request-presigner", ()=> ({ getSignedUrl: jest.fn() }))
jest.mock("../../src/config/env", ()=> ({ minio: { endpoint: "http://minio:9000", publicEndpoint: "http://localhost:9000", user: "user", password: "password", bucket: "fleettrack-documents", presignedTtl: 900 } }))
const { S3Client, PutObjectCommand }= require("@aws-sdk/client-s3")
const { getSignedUrl }= require("@aws-sdk/s3-request-presigner")
const storageService= require("../../src/services/storageService")
test("crée un client interne et un client public pour MinIO", ()=> {
  expect(S3Client).toHaveBeenCalledWith(expect.objectContaining({ endpoint: "http://minio:9000", forcePathStyle: true }))
  expect(S3Client).toHaveBeenCalledWith(expect.objectContaining({ endpoint: "http://localhost:9000" }))
})
test("uploadFile envoie le fichier dans le bucket et renvoie ses métadonnées", async ()=> {
  mockSend.mockResolvedValue({})
  const buffer= Buffer.from("pdf")
  const result= await storageService.uploadFile("orders/2026/a.pdf", buffer, "application/pdf")
  expect(PutObjectCommand).toHaveBeenCalledWith({ Bucket: "fleettrack-documents", Key: "orders/2026/a.pdf", Body: buffer, ContentType: "application/pdf" })
  expect(mockSend).toHaveBeenCalledTimes(1)
  expect(result).toEqual({ bucket: "fleettrack-documents", s3Key: "orders/2026/a.pdf", sizeBytes: 3 })
})
test("getDownloadUrl génère une URL pré-signée de 15 minutes", async ()=> {
  getSignedUrl.mockResolvedValue("http://signed-url")
  await expect(storageService.getDownloadUrl("orders/2026/a.pdf")).resolves.toBe("http://signed-url")
  expect(getSignedUrl).toHaveBeenCalledWith(expect.anything(), expect.anything(), { expiresIn: 900 })
})